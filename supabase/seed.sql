-- supabase/seed.sql: runs first on every `supabase db reset` (config.toml
-- [db.seed] sql_paths = ['./seed.sql', './seeds/*.sql']). LOCAL STACK ONLY.
--
-- It only makes sure seeding mode is OFF for this session. Seeding mode
-- (polilingo.seeding = 'on') lets demo rows be inserted and demo items be
-- written, stops approval voiding and records revisions as 'import', so it
-- is never set for a whole session: a pooled connection would carry it to
-- the next client. Each seed file turns it on with `set local` inside its
-- own transaction: supabase/seeds/10_people.sql (local test accounts) and
-- 20_content_fixture.sql (synthetic content, generated by the content repo).
select set_config('polilingo.seeding', '', false);
